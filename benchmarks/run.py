"""Decision-latency benchmark.

    python benchmarks/run.py [--n 5000] [--write docs/benchmarks.md]

Measures (a) policy evaluation only (``Shield.evaluate``) and (b) the full protected-call path for an ALLOW
(evaluation + decision event + executor + outcome event), excluding DNS and network I/O (a stub resolver is used).
Filesystem scenarios include real stat/open syscalls and are reported separately.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import statistics
import sys
import tempfile
import time

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))

from agentshield import ArgSpec, AuditLog, Policy, Shield, Tool  # noqa: E402
from agentshield.adapters import calculator_tool, file_read_tool, http_fetch_tool  # noqa: E402


def pct(sorted_ms, p):
    return sorted_ms[min(len(sorted_ms) - 1, int(p * len(sorted_ms)))]


def measure(fn, n, warmup=300):
    for _ in range(warmup):
        fn()
    out = []
    for _ in range(n):
        t = time.perf_counter_ns()
        fn()
        out.append((time.perf_counter_ns() - t) / 1e6)
    out.sort()
    return {"p50": pct(out, 0.50), "p95": pct(out, 0.95), "p99": pct(out, 0.99), "max": out[-1], "mean": statistics.fmean(out)}


def cpu_model():
    try:
        with open("/proc/cpuinfo", encoding="utf-8") as fh:
            for line in fh:
                if line.startswith("model name"):
                    return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or "unknown"


def run(n):
    tmp = tempfile.mkdtemp(prefix="agentshield-bench-")
    os.makedirs(os.path.join(tmp, "workspace"))
    with open(os.path.join(tmp, "workspace", "hello.txt"), "w") as fh:
        fh.write("hello")
    pol = {"version": 1, "tools": {
        "calculator": {"risk": "low", "decision": "ALLOW"},
        "filesystem.read": {"risk": "medium", "decision": "ALLOW", "allowed_roots": ["./workspace"]},
        "http.fetch": {"risk": "medium", "decision": "ALLOW", "allowed_hosts": ["docs.example.com"]},
        "demo.constrained": {"risk": "low", "decision": "ALLOW", "arg_constraints": {"n": {"min": 0, "max": 100}, "s": {"enum": ["a", "b", "c"]}}},
    }}
    policy = Policy.from_text(json.dumps(pol), base_dir=tmp)
    sh = Shield(policy, agent_id="bench", audit=AuditLog())
    sh.wrap(calculator_tool())
    sh.wrap(file_read_tool())
    sh.wrap(http_fetch_tool(resolver=lambda h, p: ["93.184.216.34"], connector=lambda *a: (_ for _ in ()).throw(OSError())))
    sh.wrap(Tool.from_callable(lambda n, s: None, "demo.constrained", {"n": ArgSpec("int"), "s": ArgSpec("str")}))

    file_audit = AuditLog(os.path.join(tmp, "audit.jsonl"))
    sh_file = Shield(policy, agent_id="bench", audit=file_audit)
    sh_file.wrap(calculator_tool())

    ev = sh.evaluate
    rows = [
        ("evaluate: calculator (ALLOW)", "policy only", lambda: ev("calculator", {"expression": "2 + 2 * 10"})),
        ("evaluate: custom tool with arg constraints (ALLOW)", "policy only", lambda: ev("demo.constrained", {"n": 5, "s": "a"})),
        ("evaluate: http.fetch URL checks, stub DNS (ALLOW)", "policy only (no DNS/network)", lambda: ev("http.fetch", {"url": "https://docs.example.com/a/b?q=1"})),
        ("evaluate: http.fetch SSRF attempt (DENY)", "policy only (no DNS/network)", lambda: ev("http.fetch", {"url": "https://2130706433/"})),
        ("evaluate: unknown tool (DENY)", "policy only", lambda: ev("shell.exec", {"cmd": "id"})),
        ("evaluate: filesystem.read (ALLOW)", "includes file-system syscalls", lambda: ev("filesystem.read", {"path": "hello.txt"})),
        ("evaluate: filesystem.read traversal (DENY)", "lexical, no syscalls", lambda: ev("filesystem.read", {"path": "../../etc/passwd"})),
        ("full call: calculator, in-memory audit", "eval + 2 audit events + executor", lambda: sh.call("calculator", {"expression": "2 + 2 * 10"})),
        ("full call: calculator, JSONL file audit (no fsync)", "eval + 2 audit events + file append", lambda: sh_file.call("calculator", {"expression": "2 + 2 * 10"})),
        ("full call: filesystem.read, in-memory audit", "includes file-system syscalls", lambda: sh.call("filesystem.read", {"path": "hello.txt"})),
    ]
    results = []
    for name, scope, fn in rows:
        sh.audit.events.clear()
        results.append((name, scope, measure(fn, n)))
    file_audit.close()
    return results


def render(results, n):
    lines = [
        "# Benchmarks (decision latency)", "",
        "Generated by `python benchmarks/run.py --write docs/benchmarks.md`. Numbers are **milliseconds per operation**.", "",
        "## Environment", "",
        f"- CPU: {cpu_model()} ({os.cpu_count()} vCPU)", f"- Python: {platform.python_version()} ({platform.python_implementation()})",
        f"- OS: {platform.platform()}", f"- Iterations per scenario: {n} (after 300 warm-up iterations), single thread",
        "- Policy: 4 tools. Audit: in-memory unless stated. DNS and network I/O are excluded (stub resolver/connector).", "",
        "## Results", "", "| Scenario | Scope | p50 | p95 | p99 | max |", "|---|---|---:|---:|---:|---:|",
    ]
    for name, scope, r in results:
        lines.append(f"| {name} | {scope} | {r['p50']:.4f} | {r['p95']:.4f} | {r['p99']:.4f} | {r['max']:.3f} |")
    lines += [
        "", "## Reading these numbers", "",
        "- **PRD target:** p95 policy evaluation < 10 ms for local, in-process policies, measured excluding DNS and file I/O. "
        "Every `policy only` row is far below that on this machine.",
        "- Real DNS resolution and real file/network I/O dominate end-to-end time in production and are intentionally outside the target.",
        "- `fsync` on the audit log is off by default; enabling it (`AuditLog(path, fsync=True)`) trades latency for durability.",
        "- These are single-machine microbenchmarks; treat them as a baseline for regression tracking, not a promise for other hardware.", "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=5000)
    ap.add_argument("--write")
    a = ap.parse_args()
    res = run(a.n)
    text = render(res, a.n)
    if a.write:
        with open(a.write, "w", encoding="utf-8") as fh:
            fh.write(text)
    print(text)
